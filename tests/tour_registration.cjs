const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const source = fs.readFileSync('src/lib/tourRegistration.ts', 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS }}).outputText;
const mod = { exports: {} };
new Function('exports', 'module', js)(mod.exports, mod);
const { isJdtEligible, validateEntry, TOUR_STOPS } = mod.exports;
for (const date of ['2012-03-14', '2021-03-13', '2016-02-29']) assert.equal(isJdtEligible(date), true, date);
for (const date of ['2012-03-13', '2021-03-14', '2016-02-30', '', '2020-13-01']) assert.equal(isJdtEligible(date), false, date);
const dancer = { name: 'Dancer', alias: '', country: 'France', email: 'one@example.com', birthDate: '2015-01-01' };
const entry = { stop: 'milan', category: 'Junior Dance Tour', teamName: '', dancers: [dancer], guardianName: 'Parent', guardianEmail: 'parent@example.com', guardianPhone: '+33123456789', guardianConsent: true, consent: true };
assert.equal(validateEntry(entry), null);
assert.ok(validateEntry({ ...entry, stop: 'london' }));
assert.ok(validateEntry({ ...entry, guardianConsent: false }));
assert.ok(validateEntry({ ...entry, consent: false }));
assert.ok(validateEntry({ ...entry, dancers: [{ ...dancer, birthDate: '2012-03-13' }] }));
assert.ok(validateEntry({ ...entry, category: 'Hip Hop' }));
const duo = { ...entry, stop: 'london', category: 'Krump', dancers: [dancer, { ...dancer, name: 'Partner', email: 'two@example.com' }] };
assert.equal(validateEntry(duo), null);
assert.ok(validateEntry({ ...duo, category: 'House' }));
assert.ok(validateEntry({ ...duo, dancers: [dancer, dancer] }));
assert.deepEqual(TOUR_STOPS.filter(s => s.junior).map(s => s.slug), ['chongqing','milan','paris']);
console.log('Tour registration: age boundaries, category eligibility, duo and guardian validation passed.');
